CREATE TABLE IF NOT EXISTS probe_plan_versions (
    id VARCHAR(36) PRIMARY KEY,
    organization_id VARCHAR(36) NOT NULL,
    brand_id VARCHAR(36) NOT NULL,
    brand_scope_id VARCHAR(36) NOT NULL,
    version_no INT NOT NULL,
    status_code TINYINT NOT NULL DEFAULT 1 COMMENT '0=DISABLED,1=ACTIVE',
    is_current TINYINT(1) NOT NULL DEFAULT 1,
    config_generation_snapshot INT NOT NULL DEFAULT 0,
    active_recurring_probe_count INT NOT NULL DEFAULT 0,
    estimated_immediate_credits INT NOT NULL DEFAULT 0,
    estimated_recurring_credits_per_cycle INT NOT NULL DEFAULT 0,
    snapshot_json JSON NULL,
    created_by_user_id VARCHAR(36) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_probe_plan_versions_scope_version (brand_scope_id, version_no),
    INDEX idx_probe_plan_versions_scope_current (brand_scope_id, is_current, status_code),
    INDEX idx_probe_plan_versions_org_scope (organization_id, brand_scope_id),
    CONSTRAINT fk_probe_plan_versions_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
    CONSTRAINT fk_probe_plan_versions_brand FOREIGN KEY (brand_id) REFERENCES brands(id) ON DELETE CASCADE,
    CONSTRAINT fk_probe_plan_versions_scope FOREIGN KEY (brand_scope_id) REFERENCES brand_scopes(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS probe_plan_records (
    id VARCHAR(36) PRIMARY KEY,
    organization_id VARCHAR(36) NOT NULL,
    brand_id VARCHAR(36) NOT NULL,
    brand_scope_id VARCHAR(36) NOT NULL,
    plan_version_id VARCHAR(36) NOT NULL,
    record_no INT NOT NULL,
    change_type_code VARCHAR(32) NOT NULL COMMENT 'INITIAL_CONFIRM/SCHEDULED_RUN/CONTROLLED_RERUN/ADD_PROBES/PAUSE_BATCH/RESUME_BATCH/DISABLE_PROBES/ONE_TIME_RUN',
    execute_mode_code VARCHAR(32) NOT NULL COMMENT 'ONE_TIME/RECURRING',
    status_code TINYINT NOT NULL DEFAULT 1 COMMENT '0=CANCELLED,1=CONFIRMED,2=APPLIED',
    immediate_estimated_credits INT NOT NULL DEFAULT 0,
    recurring_estimated_credits_per_cycle INT NOT NULL DEFAULT 0,
    triggered_run_id VARCHAR(36) NULL,
    effective_from_cycle_at DATETIME NULL,
    summary_json JSON NULL,
    created_by_user_id VARCHAR(36) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_probe_plan_records_scope_record (brand_scope_id, record_no),
    INDEX idx_probe_plan_records_scope_created (brand_scope_id, created_at),
    INDEX idx_probe_plan_records_version (plan_version_id),
    INDEX idx_probe_plan_records_run (triggered_run_id),
    CONSTRAINT fk_probe_plan_records_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
    CONSTRAINT fk_probe_plan_records_brand FOREIGN KEY (brand_id) REFERENCES brands(id) ON DELETE CASCADE,
    CONSTRAINT fk_probe_plan_records_scope FOREIGN KEY (brand_scope_id) REFERENCES brand_scopes(id) ON DELETE CASCADE,
    CONSTRAINT fk_probe_plan_records_version FOREIGN KEY (plan_version_id) REFERENCES probe_plan_versions(id) ON DELETE CASCADE,
    CONSTRAINT fk_probe_plan_records_run FOREIGN KEY (triggered_run_id) REFERENCES diagnosis_tasks(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS probe_plan_record_items (
    id VARCHAR(36) PRIMARY KEY,
    record_id VARCHAR(36) NOT NULL,
    plan_version_id VARCHAR(36) NOT NULL,
    probe_id VARCHAR(36) NULL,
    topic_id VARCHAR(36) NULL,
    action_code VARCHAR(32) NOT NULL COMMENT 'ADD/KEEP/PAUSE/DISABLE/RUN_ONCE',
    execute_mode_code VARCHAR(32) NOT NULL COMMENT 'ONE_TIME/RECURRING',
    seq_no_snapshot INT NULL,
    probe_text_snapshot TEXT NULL,
    source_code_snapshot TINYINT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_probe_plan_record_items_record (record_id, seq_no_snapshot),
    INDEX idx_probe_plan_record_items_version (plan_version_id),
    INDEX idx_probe_plan_record_items_probe (probe_id),
    INDEX idx_probe_plan_record_items_topic (topic_id),
    CONSTRAINT fk_probe_plan_record_items_record FOREIGN KEY (record_id) REFERENCES probe_plan_records(id) ON DELETE CASCADE,
    CONSTRAINT fk_probe_plan_record_items_version FOREIGN KEY (plan_version_id) REFERENCES probe_plan_versions(id) ON DELETE CASCADE,
    CONSTRAINT fk_probe_plan_record_items_probe FOREIGN KEY (probe_id) REFERENCES brand_space_prompts(id) ON DELETE SET NULL,
    CONSTRAINT fk_probe_plan_record_items_topic FOREIGN KEY (topic_id) REFERENCES brand_space_topics(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
