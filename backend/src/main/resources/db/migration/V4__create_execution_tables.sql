CREATE TABLE IF NOT EXISTS diagnosis_tasks (
    id VARCHAR(36) PRIMARY KEY,
    organization_id VARCHAR(36) NOT NULL,
    brand_id VARCHAR(36) NULL,
    brand_scope_id VARCHAR(36) NULL,
    requested_by_user_id VARCHAR(36) NOT NULL,
    requested_by_membership_id VARCHAR(36) NULL,
    billing_quota_account_id VARCHAR(36) NULL,
    rerun_root_task_id VARCHAR(36) NULL,
    rerun_of_task_id VARCHAR(36) NULL,
    rerun_seq_no INT NOT NULL DEFAULT 0,
    plan_id VARCHAR(36) NULL,
    source_code TINYINT NOT NULL DEFAULT 0 COMMENT '0=MANUAL,1=TRACKING,2=SYSTEM',
    target_probe_count INT NOT NULL,
    realtime_search_enabled TINYINT(1) NOT NULL DEFAULT 0,
    target_model_product VARCHAR(128) NULL,
    engine_version VARCHAR(32) NOT NULL,
    billing_mode_code TINYINT NOT NULL DEFAULT 0 COMMENT '0=ONE_TIME,1=SUBSCRIPTION,2=CONTRACT',
    billing_policy_version VARCHAR(32) NOT NULL DEFAULT 'v1',
    status_code TINYINT NOT NULL COMMENT '0=CREATED,1=RUNNING,2=COMPLETED,3=FAILED,4=CANCELLED,5=PARTIAL',
    progress_percent DECIMAL(5,2) NOT NULL DEFAULT 0,
    sampling_generated_count INT NOT NULL DEFAULT 0,
    sampling_completed_count INT NOT NULL DEFAULT 0,
    sampling_failed_count INT NOT NULL DEFAULT 0,
    sampling_skipped_count INT NOT NULL DEFAULT 0,
    total_cost_yuan DECIMAL(18,6) NOT NULL DEFAULT 0,
    search_requested_count INT NOT NULL DEFAULT 0,
    search_satisfied_count INT NOT NULL DEFAULT 0,
    locale VARCHAR(32) NOT NULL DEFAULT 'zh-CN',
    language VARCHAR(32) NOT NULL DEFAULT 'zh-CN',
    diagnosis_goal VARCHAR(255) NULL,
    brand_name_snapshot VARCHAR(200) NOT NULL,
    category_snapshot VARCHAR(200) NOT NULL,
    official_website_snapshot VARCHAR(500) NULL,
    task_order_json JSON NOT NULL,
    task_metadata_json JSON NULL,
    charge_policy_snapshot_json JSON NULL,
    started_at DATETIME NULL,
    completed_at DATETIME NULL,
    cancelled_at DATETIME NULL,
    failure_reason_code VARCHAR(64) NULL,
    failure_message TEXT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_diagnosis_tasks_org_created (organization_id, created_at),
    INDEX idx_diagnosis_tasks_status_created (status_code, created_at),
    INDEX idx_diagnosis_tasks_scope_created (brand_scope_id, created_at),
    CONSTRAINT fk_diagnosis_tasks_organization FOREIGN KEY (organization_id) REFERENCES organizations(id),
    CONSTRAINT fk_diagnosis_tasks_brand FOREIGN KEY (brand_id) REFERENCES brands(id) ON DELETE SET NULL,
    CONSTRAINT fk_diagnosis_tasks_scope FOREIGN KEY (brand_scope_id) REFERENCES brand_scopes(id) ON DELETE SET NULL,
    CONSTRAINT fk_diagnosis_tasks_requested_user FOREIGN KEY (requested_by_user_id) REFERENCES users(id),
    CONSTRAINT fk_diagnosis_tasks_requested_membership FOREIGN KEY (requested_by_membership_id) REFERENCES organization_memberships(id) ON DELETE SET NULL,
    CONSTRAINT fk_diagnosis_tasks_billing_quota_account FOREIGN KEY (billing_quota_account_id) REFERENCES quota_accounts(id) ON DELETE SET NULL,
    CONSTRAINT fk_diagnosis_tasks_rerun_root FOREIGN KEY (rerun_root_task_id) REFERENCES diagnosis_tasks(id) ON DELETE SET NULL,
    CONSTRAINT fk_diagnosis_tasks_rerun_of FOREIGN KEY (rerun_of_task_id) REFERENCES diagnosis_tasks(id) ON DELETE SET NULL,
    CONSTRAINT fk_diagnosis_tasks_plan FOREIGN KEY (plan_id) REFERENCES plan_catalog(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

